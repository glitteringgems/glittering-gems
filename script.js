// ==========================================
// SHOPPING CART MANAGEMENT
// ==========================================

let cart = JSON.parse(localStorage.getItem('glitteringGemsCart')) || [];

function updateCartCount() {
    const cartCount = document.querySelector('.cart-count');
    if (cartCount) {
        cartCount.textContent = cart.length;
    }
}

function addToCart(productId) {
    const product = findProductById(productId);
    if (product) {
        cart.push(product);
        localStorage.setItem('glitteringGemsCart', JSON.stringify(cart));
        updateCartCount();
        showNotification('Added to cart!', 'success');
    }
}

function removeFromCart(index) {
    cart.splice(index, 1);
    localStorage.setItem('glitteringGemsCart', JSON.stringify(cart));
    updateCartCount();
}

function findProductById(id) {
    for (let category in products) {
        const product = products[category].find(p => p.id === id);
        if (product) return product;
    }
    return null;
}

function showNotification(message, type = 'info') {
    const notification = document.createElement('div');
    notification.className = `notification ${type}`;
    notification.textContent = message;
    notification.style.cssText = `
        position: fixed;
        top: 20px;
        right: 20px;
        background: ${type === 'success' ? '#4CAF50' : '#2196F3'};
        color: white;
        padding: 15px 20px;
        border-radius: 5px;
        z-index: 10000;
        animation: slideIn 0.3s ease;
    `;
    document.body.appendChild(notification);
    setTimeout(() => notification.remove(), 2000);
}

// ==========================================
// FEATURED PRODUCTS
// ==========================================

function loadFeaturedProducts() {
    const featured = document.getElementById('featuredProducts');
    if (!featured) return;

    const allProducts = [];
    for (let category in products) {
        allProducts.push(...products[category]);
    }

    // Get random 8 products
    const shuffled = allProducts.sort(() => 0.5 - Math.random()).slice(0, 8);

    featured.innerHTML = shuffled.map(product => createProductCard(product)).join('');
}

function createProductCard(product) {
    return `
        <div class="product-card">
            <div class="product-image">${product.emoji}</div>
            <div class="product-info">
                <div class="product-category">${product.category}</div>
                <div class="product-name">${product.name}</div>
                <div class="product-metal">Metal: ${product.metal}</div>
                <div class="product-price">₹${product.price.toLocaleString()}</div>
                <div class="product-actions">
                    <button class="product-btn btn-add-cart" onclick="addToCart('${product.id}')">Add to Cart</button>
                    <button class="product-btn btn-wishlist" onclick="addToWishlist('${product.id}')">
                        <i class="fas fa-heart"></i>
                    </button>
                </div>
            </div>
        </div>
    `;
}

// ==========================================
// WISHLIST MANAGEMENT
// ==========================================

let wishlist = JSON.parse(localStorage.getItem('glitteringGemsWishlist')) || [];

function addToWishlist(productId) {
    const product = findProductById(productId);
    if (product) {
        if (!wishlist.find(p => p.id === productId)) {
            wishlist.push(product);
            localStorage.setItem('glitteringGemsWishlist', JSON.stringify(wishlist));
            showNotification('Added to wishlist!', 'success');
        } else {
            showNotification('Already in wishlist!', 'info');
        }
    }
}

// ==========================================
// PRODUCTS PAGE FUNCTIONALITY
// ==========================================

function loadProducts() {
    const productsGrid = document.getElementById('productsGrid');
    if (!productsGrid) return;

    const params = new URLSearchParams(window.location.search);
    const category = params.get('category') || 'rings';

    const categoryProducts = products[category] || [];
    productsGrid.innerHTML = categoryProducts.map(product => createProductCard(product)).join('');
}

function filterByMetal(metal) {
    const params = new URLSearchParams(window.location.search);
    const category = params.get('category') || 'rings';
    const productsGrid = document.getElementById('productsGrid');

    const filtered = metal === 'all' 
        ? products[category]
        : products[category].filter(p => p.metal === metal);

    productsGrid.innerHTML = filtered.map(product => createProductCard(product)).join('');
}

// ==========================================
// CART PAGE FUNCTIONALITY
// ==========================================

function displayCart() {
    const cartContainer = document.getElementById('cartContainer');
    if (!cartContainer) return;

    if (cart.length === 0) {
        cartContainer.innerHTML = '<p style="text-align: center; padding: 2rem;">Your cart is empty</p>';
        return;
    }

    let total = 0;
    const cartHTML = cart.map((product, index) => {
        total += product.price;
        return `
            <div class="cart-item">
                <div class="item-details">
                    <h3>${product.name}</h3>
                    <p>Metal: ${product.metal}</p>
                    <p class="price">₹${product.price.toLocaleString()}</p>
                </div>
                <button onclick="removeFromCart(${index})" class="btn-remove">Remove</button>
            </div>
        `;
    }).join('');

    cartContainer.innerHTML = cartHTML + `
        <div class="cart-summary">
            <h2>Total: ₹${total.toLocaleString()}</h2>
            <button class="btn btn-primary" onclick="checkout()">Proceed to Checkout</button>
        </div>
    `;
}

function checkout() {
    if (cart.length === 0) {
        showNotification('Cart is empty!', 'info');
        return;
    }
    showNotification('Thank you for your order! Our team will contact you soon.', 'success');
    cart = [];
    localStorage.setItem('glitteringGemsCart', JSON.stringify(cart));
    updateCartCount();
    setTimeout(() => window.location.href = 'index.html', 2000);
}

